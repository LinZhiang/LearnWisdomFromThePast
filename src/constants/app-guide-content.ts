export function findGuideArticle(sectionId: string, articleId: string): {
  section: GuideSection
  article: GuideArticle
} | null {
  const section = APP_GUIDE_SECTIONS.find((s) => s.id === sectionId)
  if (!section) return null
  const article = section.articles.find((a) => a.id === articleId)
  if (!article) return null
  return { section, article }
}

export function isGuideSectionSingleArticle(section: GuideSection): boolean {
  return section.articles.length === 1
}

export const DEFAULT_GUIDE_SELECTION = {
  sectionId: APP_GUIDE_SECTIONS[0]!.id,
  articleId: APP_GUIDE_SECTIONS[0]!.articles[0]!.id,
}
